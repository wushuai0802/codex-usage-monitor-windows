import assert from 'node:assert/strict';
import { SourceCache, quotaCacheKey, retentionOrder, moveRetention } from '../native-overlay/source-cache.mjs';

const start = 1793960000000;
const rows = [{ id: 'remaining', value: '42' }];
const cache = new SourceCache();
cache.resolve('paw', { status: 'ready', fetchedAt: start }, rows, start);
cache.dirty = false;
cache.resolve('paw', { status: 'ready', fetchedAt: start }, rows, start + 600000);
assert.equal(cache.dirty, false, 'Rendering the same observation does not rewrite the cache.');
cache.resolve('official', { status: 'ready', fetchedAt: start + 600000 }, rows, start + 600000);
const restarted = new SourceCache(cache.serialize(), start + 850000);
const cached = restarted.resolve('paw', { status: 'loading' }, [], start + 850000);
assert.equal(cached.status, 'stale');
assert.match(cached.rows[0].detail, /缓存读数/);
assert.equal(cached.readAt, start, 'An official refresh cannot renew Paw.');
cached.rows[0].value = 'changed';
assert.equal(restarted.entries.paw.rows[0].value, '42', 'Rendering never mutates persisted rows.');
assert.equal(restarted.resolve('paw', { status: 'loading' }, [], start + 900001).cached, false);
assert.equal(restarted.resolve('official', { status: 'loading' }, [], start + 900001).cached, true);
assert.equal(new SourceCache({ at: start, officialRows: rows }, start).resolve('official', { status: 'loading' }, [], start).cached, false);
assert.notEqual(quotaCacheKey('gemini-4-argon-high'), quotaCacheKey('gemini-3.8-flash-high'));
assert.notEqual(quotaCacheKey('claude-opus-5-5-high'), quotaCacheKey('claude-sonnet-5-5-high'), 'Model eligibility is isolated inside a shared AG group.');
assert.notEqual(quotaCacheKey('gpt-oss-120b-medium'), quotaCacheKey('gpt-6-astra'));
const cn = cache.resolve('wb:cn', { status: 'ready', fetchedAt: start, dataAt: start - 86400000 }, rows, start);
assert.equal(cn.sourceAt, start - 86400000, 'Reading CN does not refresh the upstream balance time.');
assert.equal(cn.readAt, start);
cache.resolve('future', { status: 'ready', fetchedAt: start + 300000 }, rows, start);
assert.equal(cache.entries.future, undefined);
assert.deepEqual(retentionOrder(['session:currentTaskTokens', 'model-quota:remaining', 'session:outputSpeed']), ['session:outputSpeed', 'model-quota:remaining', 'session:currentTaskTokens']);
assert.deepEqual(retentionOrder(['session:outputSpeed', 'model-quota:remaining'], ['model-quota:remaining']), ['model-quota:remaining', 'session:outputSpeed']);
console.log('PASS: independent cache age, restart, CN source time, model isolation and priority.');
assert.deepEqual(moveRetention(['a', 'b'], ['a', 'hidden', 'b'], 'b', -1), ['b', 'a', 'hidden'], 'Arrows move between visible entries without losing inactive priorities.');
assert.equal(moveRetention(['a'], [], 'a', -1), null);
